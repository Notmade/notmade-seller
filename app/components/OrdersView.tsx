"use client";

import { useCallback, useEffect, useMemo, useState, type KeyboardEvent } from "react";
import {
  api, fmtDate, fmtDateTime, REJECT_REASONS,
  type Order, type RejectReason, type ReturnRequest, type UnboxingVideo,
} from "../lib/seller-api";
import { AED, formatMoney, type Currency } from "../lib/currency";
import { ORDER_TABS, orderInTab, sellerShips, tabForParam, validTrackingId, type OrderTab } from "../lib/order-tabs";
import { Alert, Badge, Button, Card, EmptyState, Field, Modal, PageHeader, PageSkeleton, RED, Skeleton } from "./portal-ui";
import OrderTimeline from "./OrderTimeline";

const EMPTY: Record<OrderTab, { title: string; sub: string }> = {
  new: { title: "No new orders", sub: "New orders land here for you to accept. Keep your stock up to date so shoppers can order." },
  pack: { title: "Nothing to pack", sub: "Orders you accept wait here until they are ready." },
  shipped: { title: "Nothing on the way", sub: "Orders show here once they leave you." },
  delivered: { title: "No delivered orders yet", sub: "Delivered orders start your settlement." },
  returns: { title: "No returns", sub: "Return and exchange requests show here." },
  cancelled: { title: "No cancelled orders", sub: "Orders you reject or that are cancelled show here." },
};
const VIDEO_LABEL: Record<string, string> = { pending_review: "Pending review", approved: "Approved", rejected: "Rejected" };

type VideoState = { loading: true } | { loading: false; video: UnboxingVideo | null; error?: string };

function useNow(ms = 30_000) {
  const [now, setNow] = useState(() => Date.now());
  useEffect(() => { const t = setInterval(() => setNow(Date.now()), ms); return () => clearInterval(t); }, [ms]);
  return now;
}

function SlaChip({ due, now }: { due: string; now: number }) {
  const left = new Date(due).getTime() - now;
  const overdue = left <= 0;
  const h = Math.floor(Math.abs(left) / 3_600_000);
  const m = Math.floor((Math.abs(left) % 3_600_000) / 60_000);
  const txt = overdue ? `Overdue by ${h ? `${h}h ` : ""}${m}m` : `Accept within ${h ? `${h}h ` : ""}${m}m`;
  const urgent = overdue || left < 2 * 3_600_000;
  return (
    <span className={urgent ? "sp-chip sp-chip-red" : "sp-chip"}>
      <svg width="12" height="12" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.4" aria-hidden><circle cx="12" cy="12" r="9" /><path d="M12 7v5l3 2" /></svg>
      {txt}
    </span>
  );
}

interface Props {
  /** The seller's currency. An order in any other currency is labelled and shown in its own. */
  currency: Currency;
  title: string;
  sub: string;
}

type Payment = "all" | "cod" | "prepaid";
type Period = "all" | "1" | "7" | "30";
const isCod = (o: Order) => String(o.payment_method || "").toLowerCase() === "cod";

/** The signed-in seller's orders. */
export default function OrdersView({ currency, title, sub }: Props) {
  const [orders, setOrders] = useState<Order[] | null>(null);
  const [returns, setReturns] = useState<ReturnRequest[]>([]);
  const [error, setError] = useState("");
  const [tab, setTab] = useState<OrderTab>("new");
  const [focus, setFocus] = useState<string | null>(null);
  const [query, setQuery] = useState("");
  const [payment, setPayment] = useState<Payment>("all");
  const [period, setPeriod] = useState<Period>("all");
  const [tracking, setTracking] = useState<Order | null>(null);
  const [busy, setBusy] = useState<string | null>(null);
  const [rowError, setRowError] = useState<Record<string, string>>({});
  const [open, setOpen] = useState<Record<string, boolean>>({});
  const [videos, setVideos] = useState<Record<string, VideoState>>({});
  const [rejecting, setRejecting] = useState<Order | null>(null);
  const [readying, setReadying] = useState<Order | null>(null);
  const now = useNow();

  // ?tab=ready&ref=NM-… deep links from notifications and emails
  useEffect(() => {
    const p = new URLSearchParams(window.location.search);
    const t = p.get("tab");
    const fromLink = tabForParam(t);
    if (fromLink) setTab(fromLink);
    const ref = p.get("ref");
    if (ref) { setFocus(ref); setOpen(o => ({ ...o, [ref]: true })); }
  }, []);

  const load = useCallback(async (quiet = false) => {
    if (!quiet) setError("");
    try {
      const [o, r] = await Promise.all([api.orders(), api.returns().catch(() => ({ returns: [] as ReturnRequest[] }))]);
      setOrders(o.orders);
      setReturns(r.returns);
    } catch (err) {
      if (!quiet) setError(err instanceof Error ? err.message : "Could not load orders");
    }
  }, []);
  useEffect(() => { void load(); }, [load]);
  // Live: AWBs generated by NOTMADE and new orders appear without a refresh
  useEffect(() => {
    const t = setInterval(() => { if (document.visibilityState === "visible") void load(true); }, 30_000);
    return () => clearInterval(t);
  }, [load]);

  const counts = useMemo(() => {
    const c = Object.fromEntries(ORDER_TABS.map(t => [t.key, (orders ?? []).filter(o => orderInTab(o, t.key)).length])) as Record<OrderTab, number>;
    c.returns += returns.length;
    return c;
  }, [orders, returns]);

  const shown = useMemo(() => {
    const q = query.trim().toLowerCase();
    const from = period === "all" ? 0 : now - Number(period) * 86_400_000;
    return (orders ?? []).filter(o => orderInTab(o, tab))
      .filter(o => !q || o.ref_no.toLowerCase().includes(q) || o.items.some(i => i.product_name?.toLowerCase().includes(q)))
      .filter(o => payment === "all" || (payment === "cod") === isCod(o))
      .filter(o => new Date(o.created_at).getTime() >= from)
      .sort((a, b) => tab === "new"
        ? new Date(a.sla_due_at || a.created_at).getTime() - new Date(b.sla_due_at || b.created_at).getTime()
        : new Date(b.created_at).getTime() - new Date(a.created_at).getTime());
  }, [orders, tab, query, payment, period, now]);

  const replaceOrder = (order: Order) => setOrders(os => (os ?? []).map(o => o.ref_no === order.ref_no ? order : o));

  const run = async (refNo: string, fn: () => Promise<void>) => {
    setBusy(refNo);
    setRowError(e => ({ ...e, [refNo]: "" }));
    try { await fn(); }
    catch (err) { setRowError(e => ({ ...e, [refNo]: err instanceof Error ? err.message : "Something went wrong" })); }
    finally { setBusy(null); }
  };

  const accept = (refNo: string) => run(refNo, async () => { replaceOrder((await api.acceptOrder(refNo)).order); });

  const ready = (refNo: string) => run(refNo, async () => { replaceOrder((await api.markReady(refNo)).order); });

  const downloadLabel = (refNo: string) => run(refNo, async () => {
    const res = await api.orderLabel(refNo);
    if (res.label_url) window.open(res.label_url, "_blank", "noopener");
    else if (res.manual) throw new Error(`${res.courier} label is handed over by NOTMADE at pickup.`);
    else throw new Error("The courier is still preparing the label. Try again in a minute.");
  });

  const toggleVideo = async (refNo: string) => {
    const isOpen = !open[`v-${refNo}`];
    setOpen(o => ({ ...o, [`v-${refNo}`]: isOpen }));
    const cur = videos[refNo];
    if (!isOpen || (cur && !cur.loading && !cur.error)) return;
    setVideos(v => ({ ...v, [refNo]: { loading: true } }));
    try {
      const { video } = await api.unboxingVideo(refNo);
      setVideos(v => ({ ...v, [refNo]: { loading: false, video } }));
    } catch (err) {
      setVideos(v => ({ ...v, [refNo]: { loading: false, video: null, error: err instanceof Error ? err.message : "Could not load video" } }));
    }
  };

  /** Arrow keys, Home and End move between tabs. */
  const onTabKey = (e: KeyboardEvent<HTMLDivElement>) => {
    const i = ORDER_TABS.findIndex(t => t.key === tab);
    const to = e.key === "ArrowRight" ? (i + 1) % ORDER_TABS.length : e.key === "ArrowLeft" ? (i - 1 + ORDER_TABS.length) % ORDER_TABS.length
      : e.key === "Home" ? 0 : e.key === "End" ? ORDER_TABS.length - 1 : -1;
    if (to < 0) return;
    e.preventDefault();
    setTab(ORDER_TABS[to].key);
    (e.currentTarget.children[to] as HTMLElement).focus();
  };

  if (error) return <Alert>{error}</Alert>;
  if (!orders) return <PageSkeleton stats={0} />;

  return (
    <div>
      <PageHeader title={title} sub={sub} />

      <div className="sp-toolbar">
        <input className="sp-search" placeholder="Search order or product" value={query} onChange={e => setQuery(e.target.value)} aria-label="Search orders" />
        <select aria-label="Payment" value={payment} onChange={e => setPayment(e.target.value as Payment)}>
          <option value="all">All payments</option>
          <option value="cod">Cash on delivery</option>
          <option value="prepaid">Prepaid</option>
        </select>
        <select aria-label="Order date" value={period} onChange={e => setPeriod(e.target.value as Period)}>
          <option value="all">Any date</option>
          <option value="1">Last 24 hours</option>
          <option value="7">Last 7 days</option>
          <option value="30">Last 30 days</option>
        </select>
      </div>

      <div role="tablist" aria-label="Order status" className="sp-tabs" onKeyDown={onTabKey}>
        {ORDER_TABS.map(t => (
          <button key={t.key} role="tab" aria-selected={tab === t.key} tabIndex={tab === t.key ? 0 : -1} onClick={() => setTab(t.key)}
            className={tab === t.key ? "sp-tab active" : "sp-tab"}>
            {t.label}
            {counts[t.key] > 0 && <span className={t.key === "new" ? "sp-count sp-count-red" : "sp-count"}>{counts[t.key]}</span>}
          </button>
        ))}
      </div>

      {tab === "returns" && returns.length > 0 && (
        <Card style={{ padding: 0, marginBottom: 14 }}>
          <p style={{ padding: "14px 18px", fontSize: 14, fontWeight: 800, borderBottom: "1px solid #EEEEEE" }}>Return and exchange requests</p>
          {returns.map(r => (
            <div key={r.id} style={{ display: "flex", gap: 12, alignItems: "center", flexWrap: "wrap", padding: "12px 18px", borderBottom: "1px solid #F3F3F3" }}>
              <div style={{ flex: 1, minWidth: 200 }}>
                <p style={{ fontSize: 14, fontWeight: 700 }}>{r.product_name || r.order_ref || "Return"} <span style={{ color: "#888", fontWeight: 500 }}>· {r.type}</span></p>
                <p style={{ fontSize: 12, color: "#777", marginTop: 2 }}>{r.reason || "—"}{r.size_ordered && ` · size ${r.size_ordered}${r.size_requested ? ` → ${r.size_requested}` : ""}`} · {fmtDate(r.created_at)}</p>
              </div>
              <Badge status={r.status} />
            </div>
          ))}
        </Card>
      )}

      {shown.length === 0 ? (
        tab === "returns" && returns.length ? null : <EmptyState title={(query || payment !== "all" || period !== "all") && counts[tab] > 0 ? "No orders match these filters." : EMPTY[tab].title}
          sub={(query || payment !== "all" || period !== "all") && counts[tab] > 0 ? undefined : EMPTY[tab].sub}
          action={(query || payment !== "all" || period !== "all") && counts[tab] > 0
            ? <Button variant="secondary" onClick={() => { setQuery(""); setPayment("all"); setPeriod("all"); }}>Clear filters</Button>
            : tab === "new" ? <a href="/dashboard/products" className="sp-btn-red">Check your catalogue</a> : undefined} />
      ) : (
        <div style={{ display: "flex", flexDirection: "column", gap: 14 }}>
          {shown.map(o => {
            const actionable = o.seller_status === "awaiting" && !o.multi_seller;
            const c = o.commission;
            const money = (n: number | null | undefined) => formatMoney(n, c.currency);
            const video = videos[o.ref_no];
            return (
              <Card key={o.ref_no} style={{ padding: 0, overflow: "hidden", outline: focus === o.ref_no ? `2px solid ${RED}` : undefined }}>
                <div className="sp-order-head">
                  <div style={{ minWidth: 0 }}>
                    <p style={{ fontSize: 15, fontWeight: 800 }}>{o.ref_no}</p>
                    <p style={{ fontSize: 12, color: "#888", marginTop: 2 }}>
                      {fmtDateTime(o.created_at)}{o.city && ` · ${o.city}`}{o.pincode && ` ${o.pincode}`}
                    </p>
                  </div>
                  <div style={{ display: "flex", gap: 6, flexWrap: "wrap", alignItems: "center" }}>
                    {o.bucket === "new" && o.sla_due_at && <SlaChip due={o.sla_due_at} now={now} />}
                    {c.currency !== currency && <span className="sp-chip">{c.currency}</span>}
                    <span className="sp-chip">{isCod(o) ? "COD" : "Prepaid"}</span>
                    <Badge status={o.bucket === "cancelled" ? "cancelled" : o.stage === "awb" ? "packed" : o.status} label={o.bucket === "ready" ? (o.manual_courier && o.courier_assigned ? "Courier assigned" : o.waybill ? "AWB ready" : "Ready for pickup") : undefined} />
                  </div>
                </div>

                <ul style={{ listStyle: "none", margin: 0, padding: "4px 18px" }}>
                  {o.items.map((i, idx) => (
                    <li key={idx} style={{ display: "flex", gap: 12, alignItems: "center", padding: "10px 0", borderBottom: idx < o.items.length - 1 ? "1px solid #F3F3F3" : undefined }}>
                      {i.image
                        // eslint-disable-next-line @next/next/no-img-element
                        ? <img src={i.image} alt="" width={52} height={64} style={{ width: 52, height: 64, objectFit: "cover", borderRadius: 8, background: "#F3F3F3" }} />
                        : <div style={{ width: 52, height: 64, borderRadius: 8, background: "#F3F3F3" }} />}
                      <div style={{ flex: 1, minWidth: 0 }}>
                        <p style={{ fontSize: 14, fontWeight: 700 }}>{i.product_name}</p>
                        <p style={{ fontSize: 12, color: "#777", marginTop: 2 }}>{i.label && `${i.label} · `}Qty {i.quantity}</p>
                      </div>
                      <p style={{ fontSize: 14, fontWeight: 700, whiteSpace: "nowrap" }}>
                        {money(c.currency === AED ? (i.market_unit_price ?? i.unit_price) * i.quantity : i.line_total)}
                      </p>
                    </li>
                  ))}
                </ul>

                <div className="sp-money">
                  <div><span>Order value</span><strong>{money(c.gross)}</strong></div>
                  <div><span>Commission {c.pct != null ? `${c.pct}%` : ""} · {c.label}{c.snapshot ? " · locked" : ""}</span><strong style={{ color: RED }}>{c.commission != null ? `−${money(c.commission)}` : "—"}</strong></div>
                  <div><span>Your payout</span><strong>{c.payout != null ? money(c.payout) : "—"}</strong></div>
                  <div><span>Settlement</span><strong>{o.settlement_date ? fmtDate(o.settlement_date) : o.settlement_days ? `Within ${o.settlement_days} days` : "—"}</strong></div>
                </div>

                {o.manual_courier && o.courier_assigned && o.courier && (
                  // UAE: courier partner assigned by NOTMADE; tracking number may come later; no label to print
                  <div className="sp-awb">
                    <div>
                      <p style={{ fontSize: 11, color: "#888", fontWeight: 600, letterSpacing: ".06em" }}>COURIER PARTNER</p>
                      <p style={{ fontSize: 16, fontWeight: 800 }}>{o.courier}</p>
                      <p style={{ fontSize: 12, color: "#777", marginTop: 2 }}>
                        {o.waybill ? <>Tracking <span style={{ fontFamily: "var(--font-space-mono), monospace" }}>{o.waybill}</span></> : "Tracking number not issued yet"}
                      </p>
                      {o.pickup_note && <p style={{ fontSize: 13, color: "#333", marginTop: 6 }}>Pickup note: {o.pickup_note}</p>}
                    </div>
                    <span className="sp-chip">{o.handed_over_at ? `Handed over ${fmtDateTime(o.handed_over_at)}` : o.pickup_status || "Pickup scheduled"}</span>
                  </div>
                )}

                {o.waybill && !o.manual_courier && (
                  <div className="sp-awb">
                    <div>
                      <p style={{ fontSize: 11, color: "#888", fontWeight: 600, letterSpacing: ".06em" }}>AWB · {o.courier || "Courier"}</p>
                      <p style={{ fontSize: 16, fontWeight: 800, fontFamily: "var(--font-space-mono), monospace" }}>{o.waybill}</p>
                    </div>
                    <span className="sp-chip">{o.pickup_status || o.courier_status || "Pickup scheduled"}</span>
                    {o.label_available && (
                      <Button variant="secondary" onClick={() => downloadLabel(o.ref_no)} disabled={busy === o.ref_no}>
                        {busy === o.ref_no ? "Getting label…" : "Download label"}
                      </Button>
                    )}
                  </div>
                )}

                {o.tracking_id && (
                  <div className="sp-awb">
                    <div>
                      <p style={{ fontSize: 11, color: "#888", fontWeight: 600, letterSpacing: ".06em" }}>YOUR TRACKING · {o.courier}</p>
                      <p style={{ fontSize: 16, fontWeight: 800, fontFamily: "var(--font-space-mono), monospace" }}>{o.tracking_id}</p>
                    </div>
                  </div>
                )}

                {o.bucket === "ready" && !o.waybill && !o.courier_assigned && (
                  <p className="sp-note-line">Marked ready {o.ready_at ? fmtDateTime(o.ready_at) : ""}{o.package_weight_kg ? ` · ${o.package_weight_kg} kg` : ""}. {o.region === "ae"
                    ? "NOTMADE is assigning a UAE courier partner — the courier and pickup note will show here."
                    : "NOTMADE is generating the AWB — it will show here with the label."}</p>
                )}
                {o.bucket === "cancelled" && (
                  <p className="sp-note-line" style={{ color: "#B00000" }}>{o.seller_reject_reason || o.cancel_reason || "Cancelled"}</p>
                )}
                {o.multi_seller && <p className="sp-note-line">This order has items from other sellers too. NOTMADE handles its fulfilment.</p>}

                {rowError[o.ref_no] && <div style={{ padding: "0 18px 12px" }}><Alert>{rowError[o.ref_no]}</Alert></div>}

                <div className="sp-order-foot">
                  <button type="button" className="sp-link" onClick={() => setOpen(s => ({ ...s, [o.ref_no]: !s[o.ref_no] }))} aria-expanded={!!open[o.ref_no]}>
                    {open[o.ref_no] ? "Hide progress" : "Track progress"}
                  </button>
                  {o.has_unboxing_video && (
                    <button type="button" className="sp-link" onClick={() => void toggleVideo(o.ref_no)}>
                      Unboxing video · {VIDEO_LABEL[o.unboxing_video_status || "pending_review"]}
                    </button>
                  )}
                  <div style={{ marginLeft: "auto", display: "flex", gap: 8, flexWrap: "wrap" }}>
                    {actionable && (
                      <>
                        <Button variant="danger" onClick={() => setRejecting(o)} disabled={busy === o.ref_no}>Reject</Button>
                        <Button onClick={() => void accept(o.ref_no)} disabled={busy === o.ref_no}>
                          {busy === o.ref_no ? "Accepting…" : "Accept order"}
                        </Button>
                      </>
                    )}
                    {o.bucket === "accepted" && !o.multi_seller && <a href={`/dashboard/orders/${encodeURIComponent(o.ref_no)}/slip`} className="sp-btn-line">Packing slip</a>}
                    {o.bucket === "accepted" && !o.multi_seller && (sellerShips(o)
                      ? <Button onClick={() => setTracking(o)}>Enter tracking</Button>
                      : <>
                          <Button variant="ghost" onClick={() => setReadying(o)} disabled={busy === o.ref_no}>Add weight</Button>
                          <Button onClick={() => void ready(o.ref_no)} disabled={busy === o.ref_no}>{busy === o.ref_no ? "Marking…" : "Mark as ready"}</Button>
                        </>)}
                    {o.bucket === "ready" && !o.multi_seller && <a href={`/dashboard/orders/${encodeURIComponent(o.ref_no)}/slip`} className="sp-btn-line">Packing slip</a>}
                  </div>
                </div>

                {open[o.ref_no] && (
                  <div style={{ padding: "4px 18px 18px" }}>
                    <OrderTimeline steps={o.timeline} cancelled={o.bucket === "cancelled"} />
                  </div>
                )}
                {open[`v-${o.ref_no}`] && (
                  <div style={{ padding: "0 18px 18px" }}>
                    {!video || video.loading ? <Skeleton height={180} width="100%" radius={12} style={{ maxWidth: 420 }} />
                      : video.error ? <Alert>{video.error}</Alert>
                      : video.video?.url ? <video src={video.video.url} controls playsInline style={{ width: "100%", maxWidth: 420, borderRadius: 12, background: "#000" }} />
                      : <p style={{ fontSize: 13, color: "#888" }}>Video is not available right now.</p>}
                  </div>
                )}
              </Card>
            );
          })}
        </div>
      )}

      {rejecting && (
        <RejectModal order={rejecting} onClose={() => setRejecting(null)}
          onRejected={o => { replaceOrder(o); setRejecting(null); }} />
      )}
      {tracking && (
        <TrackingModal order={tracking} onClose={() => setTracking(null)}
          onSaved={o => { replaceOrder(o); setTracking(null); }} />
      )}
      {readying && (
        <ReadyModal order={readying} onClose={() => setReadying(null)}
          onReady={o => { replaceOrder(o); setReadying(null); }} />
      )}
    </div>
  );
}

function TrackingModal({ order, onClose, onSaved }: { order: Order; onClose: () => void; onSaved: (o: Order) => void }) {
  const [courier, setCourier] = useState(order.courier ?? "");
  const [number, setNumber] = useState(order.tracking_id ?? "");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const ready = courier.trim().length >= 2 && validTrackingId(number);

  const submit = async () => {
    setBusy(true); setError("");
    try {
      onSaved((await api.shipOrder(order.ref_no, { courier: courier.trim(), tracking_id: number.trim() })).order);
    } catch (err) {
      setError(err instanceof Error ? err.message : "Could not save tracking");
      setBusy(false);
    }
  };

  return (
    <Modal title={`Enter tracking · ${order.ref_no}`} onClose={onClose} width={460}>
      <div style={{ display: "flex", flexDirection: "column", gap: 14 }}>
        <Field label="Courier" htmlFor="track-courier"><input id="track-courier" className="sp-field" value={courier} onChange={e => setCourier(e.target.value)} maxLength={60} /></Field>
        <Field label="Tracking number" htmlFor="track-number" hint="4 to 60 letters, digits or . _ / -"><input id="track-number" className="sp-field" value={number} onChange={e => setNumber(e.target.value)} maxLength={60} autoComplete="off" /></Field>
      </div>
      {error && <div style={{ marginTop: 12 }}><Alert>{error}</Alert></div>}
      <div style={{ display: "flex", justifyContent: "flex-end", gap: 8, marginTop: 18, flexWrap: "wrap" }}>
        <Button variant="secondary" onClick={onClose} disabled={busy}>Cancel</Button>
        <Button onClick={() => void submit()} disabled={busy || !ready}>{busy ? "Saving…" : "Save and mark shipped"}</Button>
      </div>
    </Modal>
  );
}

function RejectModal({ order, onClose, onRejected }: { order: Order; onClose: () => void; onRejected: (o: Order) => void }) {
  const [reason, setReason] = useState<RejectReason>(REJECT_REASONS[0]);
  const [details, setDetails] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const tooShort = details.trim().length < 3;

  const submit = async () => {
    setBusy(true); setError("");
    try { onRejected((await api.rejectOrder(order.ref_no, reason, details.trim())).order); }
    catch (err) { setError(err instanceof Error ? err.message : "Could not reject order"); setBusy(false); }
  };

  return (
    <Modal title={`Reject ${order.ref_no}?`} onClose={onClose} width={480}>
      <p style={{ fontSize: 14, color: "#555", lineHeight: 1.55, marginBottom: 16 }}>
        The order will be cancelled, the stock goes back to your listing and the customer is told by email and WhatsApp.
      </p>
      <label htmlFor="reject-reason" style={{ display: "block", fontSize: 13, fontWeight: 600, marginBottom: 6 }}>Reason</label>
      <select id="reject-reason" value={reason} onChange={e => setReason(e.target.value as RejectReason)} className="sp-field">
        {REJECT_REASONS.map(r => <option key={r} value={r}>{r}</option>)}
      </select>
      <label htmlFor="reject-note" style={{ display: "block", fontSize: 13, fontWeight: 600, margin: "14px 0 6px" }}>Note (required)</label>
      <textarea id="reject-note" rows={3} value={details} onChange={e => setDetails(e.target.value)} maxLength={500} className="sp-field"
        placeholder={reason === "Out of stock" ? "e.g. Last piece was damaged during QC" : reason === "Can't fulfil in time" ? "e.g. Restock arrives next week" : "Tell us what happened"} />
      {error && <div style={{ marginTop: 12 }}><Alert>{error}</Alert></div>}
      <div style={{ display: "flex", justifyContent: "flex-end", gap: 8, marginTop: 18 }}>
        <Button variant="secondary" onClick={onClose} disabled={busy}>Keep order</Button>
        <Button onClick={() => void submit()} disabled={busy || tooShort} style={{ background: "#111111" }}>
          {busy ? "Rejecting…" : "Reject and cancel"}
        </Button>
      </div>
    </Modal>
  );
}

function ReadyModal({ order, onClose, onReady }: { order: Order; onClose: () => void; onReady: (o: Order) => void }) {
  const [weight, setWeight] = useState("");
  const [checks, setChecks] = useState({ packed: false, tagged: false });
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const w = weight.trim() ? Number(weight) : undefined;
  const badWeight = w !== undefined && (!Number.isFinite(w) || w <= 0 || w > 50);

  const submit = async () => {
    setBusy(true); setError("");
    try { onReady((await api.markReady(order.ref_no, w)).order); }
    catch (err) { setError(err instanceof Error ? err.message : "Could not mark ready"); setBusy(false); }
  };

  return (
    <Modal title={`Ready for pickup · ${order.ref_no}`} onClose={onClose} width={460}>
      <p style={{ fontSize: 14, color: "#555", lineHeight: 1.55, marginBottom: 16 }}>
        {order.region === "ae"
          ? <>Once you confirm, NOTMADE assigns a UAE courier partner to collect it from your address. The courier and pickup note will show here.</>
          : <>Once you confirm, NOTMADE generates the AWB and books the pickup from your address. You&apos;ll get the label here.</>}
      </p>
      {[
        { k: "packed" as const, t: "Packed in a sealed NOTMADE-ready parcel" },
        { k: "tagged" as const, t: "Tags on, invoice inside" },
      ].map(c => (
        <label key={c.k} style={{ display: "flex", gap: 10, alignItems: "center", fontSize: 14, padding: "8px 0", cursor: "pointer" }}>
          <input type="checkbox" checked={checks[c.k]} onChange={e => setChecks(s => ({ ...s, [c.k]: e.target.checked }))} style={{ width: 18, height: 18, accentColor: RED }} />
          {c.t}
        </label>
      ))}
      <label htmlFor="ready-weight" style={{ display: "block", fontSize: 13, fontWeight: 600, margin: "12px 0 6px" }}>Package weight in kg (optional)</label>
      <input id="ready-weight" inputMode="decimal" value={weight} onChange={e => setWeight(e.target.value)} placeholder="0.5" className="sp-field" />
      {badWeight && <p style={{ fontSize: 12, color: RED, marginTop: 6 }}>Enter a weight between 0 and 50 kg.</p>}
      {error && <div style={{ marginTop: 12 }}><Alert>{error}</Alert></div>}
      <div style={{ display: "flex", justifyContent: "flex-end", gap: 8, marginTop: 18 }}>
        <Button variant="secondary" onClick={onClose} disabled={busy}>Not yet</Button>
        <Button onClick={() => void submit()} disabled={busy || badWeight || !checks.packed || !checks.tagged}>
          {busy ? "Marking…" : "Mark as ready"}
        </Button>
      </div>
    </Modal>
  );
}
